/**
 * カセット未挿入時に流す内蔵 ROM（Mapper 0）。
 * 画面中央に "HERON'S COMPUTER" を表示するだけのブート画面。
 */
export function buildBootRom(): Uint8Array {
  const rom = new Uint8Array(16 + 16384 + 8192);
  rom.set(
    [
      0x4e, 0x45, 0x53, 0x1a, // NES\x1a
      0x01, // 16KB PRG
      0x01, // 8KB CHR
      0x00,
      0x00,
      0x00,
      0x00,
      0x00,
      0x00,
      0x00,
      0x00,
      0x00,
      0x00,
    ],
    0,
  );

  const prgOffset = 16;
  const chrOffset = 16 + 16384;
  const code: number[] = [];
  const emit = (...bytes: number[]) => {
    for (const b of bytes) code.push(b & 0xff);
  };
  const here = () => 0xc000 + code.length;

  emit(0x78); // SEI
  emit(0xd8); // CLD
  emit(0xa2, 0xff); // LDX #$FF
  emit(0x9a); // TXS
  emit(0xa9, 0x00);
  emit(0x8d, 0x00, 0x20); // STA $2000
  emit(0x8d, 0x01, 0x20); // STA $2001

  // VBlank ×2
  emit(0x2c, 0x02, 0x20);
  emit(0x10, 0xfb);
  emit(0x2c, 0x02, 0x20);
  emit(0x10, 0xfb);

  // Palette $3F00: bg=$0F, fg=$30
  emit(0xad, 0x02, 0x20);
  emit(0xa9, 0x3f);
  emit(0x8d, 0x06, 0x20);
  emit(0xa9, 0x00);
  emit(0x8d, 0x06, 0x20);
  emit(0xa9, 0x0f);
  emit(0x8d, 0x07, 0x20);
  emit(0xa9, 0x30);
  emit(0x8d, 0x07, 0x20);

  // Clear nametable $2000 (1024 bytes)
  emit(0xa9, 0x20);
  emit(0x8d, 0x06, 0x20);
  emit(0xa9, 0x00);
  emit(0x8d, 0x06, 0x20);
  emit(0xa9, 0x00);
  emit(0xa2, 0x04);
  emit(0xa0, 0x00);
  const clearLoop = here();
  emit(0x8d, 0x07, 0x20);
  emit(0x88);
  emit(0xd0, (clearLoop - (here() + 2)) & 0xff);
  emit(0xca);
  emit(0xd0, (clearLoop - (here() + 2)) & 0xff);

  // Text at $21CA
  emit(0xa9, 0x21);
  emit(0x8d, 0x06, 0x20);
  emit(0xa9, 0xca);
  emit(0x8d, 0x06, 0x20);
  emit(0xa2, 0x00);
  const textLoadAt = code.length;
  emit(0xbd, 0x00, 0x00); // LDA text,X (patched)
  const beqAt = code.length;
  emit(0xf0, 0x00); // BEQ afterTextLoop (patched)
  emit(0x8d, 0x07, 0x20);
  emit(0xe8);
  const bneAt = code.length;
  const textLoop = 0xc000 + textLoadAt;
  emit(0xd0, (textLoop - (0xc000 + bneAt + 2)) & 0xff);
  const afterTextLoop = here();
  code[beqAt + 1] = (afterTextLoop - (0xc000 + beqAt + 2)) & 0xff;

  emit(0xa9, 0x00);
  emit(0x8d, 0x05, 0x20);
  emit(0x8d, 0x05, 0x20);
  emit(0xa9, 0x08);
  emit(0x8d, 0x01, 0x20);
  const forever = here();
  emit(0x4c, forever & 0xff, forever >> 8);

  const textAddr = here();
  code[textLoadAt + 1] = textAddr & 0xff;
  code[textLoadAt + 2] = textAddr >> 8;

  const textData = [
    0x48, 0x45, 0x52, 0x4f, 0x4e, 0x27, 0x53, 0x20, // HERON'S
    0x43, 0x4f, 0x4d, 0x50, 0x55, 0x54, 0x45, 0x52, // COMPUTER
    0x00,
  ];
  rom.set(code, prgOffset);
  rom.set(textData, prgOffset + (textAddr - 0xc000));

  const reset = 0xc000;
  rom[prgOffset + 0x3ffa] = reset & 0xff;
  rom[prgOffset + 0x3ffb] = reset >> 8;
  rom[prgOffset + 0x3ffc] = reset & 0xff;
  rom[prgOffset + 0x3ffd] = reset >> 8;
  rom[prgOffset + 0x3ffe] = reset & 0xff;
  rom[prgOffset + 0x3fff] = reset >> 8;

  const font: Record<number, number[]> = {
    0x27: [0x18, 0x18, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00],
    0x43: [0x3c, 0x66, 0xc0, 0xc0, 0xc0, 0x66, 0x3c, 0x00],
    0x45: [0x7e, 0x60, 0x60, 0x7c, 0x60, 0x60, 0x7e, 0x00],
    0x48: [0x66, 0x66, 0x66, 0x7e, 0x66, 0x66, 0x66, 0x00],
    0x4d: [0x63, 0x77, 0x7f, 0x6b, 0x63, 0x63, 0x63, 0x00],
    0x4e: [0x63, 0x73, 0x7b, 0x6f, 0x67, 0x63, 0x63, 0x00],
    0x4f: [0x3c, 0x66, 0xc3, 0xc3, 0xc3, 0x66, 0x3c, 0x00],
    0x50: [0x7c, 0x66, 0x66, 0x7c, 0x60, 0x60, 0x60, 0x00],
    0x52: [0x7c, 0x66, 0x66, 0x7c, 0x6e, 0x63, 0x63, 0x00],
    0x53: [0x3c, 0x66, 0x60, 0x3c, 0x06, 0x66, 0x3c, 0x00],
    0x54: [0x7e, 0x18, 0x18, 0x18, 0x18, 0x18, 0x18, 0x00],
    0x55: [0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x3c, 0x00],
  };
  for (const [ascii, rows] of Object.entries(font)) {
    const tileIndex = Number(ascii);
    const tileOffset = chrOffset + tileIndex * 16;
    for (let r = 0; r < 8; r++) {
      rom[tileOffset + r] = rows[r]!;
      rom[tileOffset + r + 8] = 0x00;
    }
  }

  return rom;
}

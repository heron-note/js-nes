/**
 * カセット未挿入時に流す内蔵 ROM（Mapper 0）。
 * "HERON'S COMPUTER" とアプリバージョンを表示するブート画面。
 */

const BOOT_VERSION = (import.meta.env.VITE_APP_VERSION as string | undefined) || "0.0.0";

type FontGlyph = number[];

/** ASCII タイル番号 → 8x8 1bpp（plane0）。必要な文字だけ持つ。 */
const FONT: Record<number, FontGlyph> = {
  0x20: [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00], // space
  0x27: [0x18, 0x18, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00], // '
  0x2e: [0x00, 0x00, 0x00, 0x00, 0x00, 0x18, 0x18, 0x00], // .
  0x30: [0x3c, 0x66, 0x6e, 0x76, 0x66, 0x66, 0x3c, 0x00], // 0
  0x31: [0x18, 0x38, 0x18, 0x18, 0x18, 0x18, 0x7e, 0x00], // 1
  0x32: [0x3c, 0x66, 0x06, 0x0c, 0x18, 0x30, 0x7e, 0x00], // 2
  0x33: [0x3c, 0x66, 0x06, 0x1c, 0x06, 0x66, 0x3c, 0x00], // 3
  0x34: [0x0c, 0x1c, 0x3c, 0x6c, 0x7e, 0x0c, 0x0c, 0x00], // 4
  0x35: [0x7e, 0x60, 0x7c, 0x06, 0x06, 0x66, 0x3c, 0x00], // 5
  0x36: [0x1c, 0x30, 0x60, 0x7c, 0x66, 0x66, 0x3c, 0x00], // 6
  0x37: [0x7e, 0x06, 0x0c, 0x18, 0x30, 0x30, 0x30, 0x00], // 7
  0x38: [0x3c, 0x66, 0x66, 0x3c, 0x66, 0x66, 0x3c, 0x00], // 8
  0x39: [0x3c, 0x66, 0x66, 0x3e, 0x06, 0x0c, 0x38, 0x00], // 9
  0x43: [0x3c, 0x66, 0xc0, 0xc0, 0xc0, 0x66, 0x3c, 0x00], // C
  0x45: [0x7e, 0x60, 0x60, 0x7c, 0x60, 0x60, 0x7e, 0x00], // E
  0x48: [0x66, 0x66, 0x66, 0x7e, 0x66, 0x66, 0x66, 0x00], // H
  0x4d: [0x63, 0x77, 0x7f, 0x6b, 0x63, 0x63, 0x63, 0x00], // M
  0x4e: [0x63, 0x73, 0x7b, 0x6f, 0x67, 0x63, 0x63, 0x00], // N
  0x4f: [0x3c, 0x66, 0xc3, 0xc3, 0xc3, 0x66, 0x3c, 0x00], // O
  0x50: [0x7c, 0x66, 0x66, 0x7c, 0x60, 0x60, 0x60, 0x00], // P
  0x52: [0x7c, 0x66, 0x66, 0x7c, 0x6e, 0x63, 0x63, 0x00], // R
  0x53: [0x3c, 0x66, 0x60, 0x3c, 0x06, 0x66, 0x3c, 0x00], // S
  0x54: [0x7e, 0x18, 0x18, 0x18, 0x18, 0x18, 0x18, 0x00], // T
  0x55: [0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x3c, 0x00], // U
  0x56: [0x66, 0x66, 0x66, 0x66, 0x66, 0x3c, 0x18, 0x00], // V
};

function encodeAsciiTiles(text: string): number[] {
  const out: number[] = [];
  for (const ch of text) {
    const code = ch.charCodeAt(0);
    if (!(code in FONT)) {
      throw new Error(`boot ROM font missing glyph for U+${code.toString(16)} ('${ch}')`);
    }
    out.push(code);
  }
  out.push(0x00);
  return out;
}

/** 画面中央付近にタイトル、その下に V{version} を出す。 */
export function buildBootRom(): Uint8Array {
  const rom = new Uint8Array(16 + 16384 + 8192);
  rom.set([0x4e, 0x45, 0x53, 0x1a, 0x01, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00], 0);

  const prgOffset = 16;
  const chrOffset = 16 + 16384;
  const code: number[] = [];
  const emit = (...bytes: number[]) => {
    for (const b of bytes) code.push(b & 0xff);
  };
  const here = () => 0xc000 + code.length;

  const title = "HERON'S COMPUTER";
  const versionLine = `V${BOOT_VERSION}`.toUpperCase();
  // ネームテーブル幅 32。タイトル／バージョンとも水平中央寄せ
  const titleCol = Math.floor((32 - title.length) / 2);
  const titlePpu = 0x2000 + 14 * 32 + titleCol;
  const verCol = Math.floor((32 - versionLine.length) / 2);
  const versionPpu = 0x2000 + 16 * 32 + verCol;

  const titleBytes = encodeAsciiTiles(title);
  const versionBytes = encodeAsciiTiles(versionLine);

  emit(0x78); // SEI
  emit(0xd8); // CLD
  emit(0xa2, 0xff);
  emit(0x9a);
  emit(0xa9, 0x00);
  emit(0x8d, 0x00, 0x20);
  emit(0x8d, 0x01, 0x20);

  emit(0x2c, 0x02, 0x20);
  emit(0x10, 0xfb);
  emit(0x2c, 0x02, 0x20);
  emit(0x10, 0xfb);

  emit(0xad, 0x02, 0x20);
  emit(0xa9, 0x3f);
  emit(0x8d, 0x06, 0x20);
  emit(0xa9, 0x00);
  emit(0x8d, 0x06, 0x20);
  emit(0xa9, 0x0f);
  emit(0x8d, 0x07, 0x20);
  emit(0xa9, 0x30);
  emit(0x8d, 0x07, 0x20);

  emit(0xa9, 0x20);
  emit(0x8d, 0x06, 0x20);
  emit(0xa9, 0x00);
  emit(0x8d, 0x06, 0x20);
  emit(0xa9, 0x00);
  emit(0xa2, 0x04);
  emit(0xa0, 0x00);
  const clearLoop = here();
  emit(0x8d, 0x07, 0x20);
  emit(0x88);
  emit(0xd0, (clearLoop - (here() + 2)) & 0xff);
  emit(0xca);
  emit(0xd0, (clearLoop - (here() + 2)) & 0xff);

  /** 文字列描画: PPU addr をセットして from の NUL 終端を転送。パッチ用スロットを返す。 */
  const emitDrawString = (ppuAddr: number): { loadAt: number; beqAt: number } => {
    emit(0xa9, (ppuAddr >> 8) & 0xff);
    emit(0x8d, 0x06, 0x20);
    emit(0xa9, ppuAddr & 0xff);
    emit(0x8d, 0x06, 0x20);
    emit(0xa2, 0x00);
    const loadAt = code.length;
    emit(0xbd, 0x00, 0x00); // LDA str,X
    const beqAt = code.length;
    emit(0xf0, 0x00); // BEQ done
    emit(0x8d, 0x07, 0x20);
    emit(0xe8);
    const bneAt = code.length;
    const loop = 0xc000 + loadAt;
    emit(0xd0, (loop - (0xc000 + bneAt + 2)) & 0xff);
    const done = here();
    code[beqAt + 1] = (done - (0xc000 + beqAt + 2)) & 0xff;
    return { loadAt, beqAt };
  };

  const titleDraw = emitDrawString(titlePpu);
  const versionDraw = emitDrawString(versionPpu);

  emit(0xa9, 0x00);
  emit(0x8d, 0x05, 0x20);
  emit(0x8d, 0x05, 0x20);
  emit(0xa9, 0x08);
  emit(0x8d, 0x01, 0x20);
  const forever = here();
  emit(0x4c, forever & 0xff, forever >> 8);

  const titleAddr = here();
  code[titleDraw.loadAt + 1] = titleAddr & 0xff;
  code[titleDraw.loadAt + 2] = titleAddr >> 8;
  for (const b of titleBytes) emit(b);

  const versionAddr = here();
  code[versionDraw.loadAt + 1] = versionAddr & 0xff;
  code[versionDraw.loadAt + 2] = versionAddr >> 8;
  for (const b of versionBytes) emit(b);

  if (code.length > 0x3ffa) {
    throw new Error(`boot ROM program too large (${code.length} bytes)`);
  }

  rom.set(code, prgOffset);

  const reset = 0xc000;
  rom[prgOffset + 0x3ffa] = reset & 0xff;
  rom[prgOffset + 0x3ffb] = reset >> 8;
  rom[prgOffset + 0x3ffc] = reset & 0xff;
  rom[prgOffset + 0x3ffd] = reset >> 8;
  rom[prgOffset + 0x3ffe] = reset & 0xff;
  rom[prgOffset + 0x3fff] = reset >> 8;

  for (const [ascii, rows] of Object.entries(FONT)) {
    const tileIndex = Number(ascii);
    const tileOffset = chrOffset + tileIndex * 16;
    for (let r = 0; r < 8; r++) {
      rom[tileOffset + r] = rows[r]!;
      rom[tileOffset + r + 8] = 0x00;
    }
  }

  return rom;
}
